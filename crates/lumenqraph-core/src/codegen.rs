/// Generate a self-contained typed Python client (Python 3.10+, dataclasses,
/// stdlib `urllib.request` only) for `contract_id` from its on-chain interface.
pub fn python_client(contract_id: &str, spec: &ContractSpec) -> String {
    let mut out = String::new();
    let _ = write!(
        out,
        "\
# Typed client for the Soroban contract
#   {contract_id}
#
# Generated by Lumenqraph from the contract's on-chain interface.
# Zero dependencies: uses only Python 3.10+ stdlib (dataclasses, urllib).
#
# Regenerate any time from `GET /contracts/{contract_id}/sdk?lang=python`.

from __future__ import annotations

import json
import urllib.request
from dataclasses import dataclass
from typing import Any, Optional, Union

ADDRESS = str  # Stellar G… / C… strkey
BYTES = str    # hex-encoded bytes
INT = Union[int, str]  # large integers as decimal strings

"
    );

    // Emit dataclass per struct
    for s in &spec.structs {
        out.push('\n');
        let _ = writeln!(out, "@dataclass");
        let _ = writeln!(out, "class {}:", s.name);
        if s.fields.is_empty() {
            out.push_str("    pass\n");
        } else {
            for f in &s.fields {
                let ty = py_type(&f.ty);
                let _ = writeln!(out, "    {}: {}", py_ident(&f.name), ty);
            }
        }
    }

    // Emit simple str enums
    for e in &spec.enums {
        let cases: Vec<String> = e.cases.iter().map(|(n, _)| format!("    {} = {:?}", n, n)).collect();
        out.push('\n');
        let _ = writeln!(out, "class {}:", e.name);
        if cases.is_empty() {
            out.push_str("    pass\n");
        } else {
            for c in &cases {
                out.push_str(c);
                out.push('\n');
            }
        }
    }

    // Emit ContractClient class
    let _ = write!(
        out,
        "
class ContractClient:
    CONTRACT_ID = {contract_id:?}

    def __init__(self, base_url: str, api_key: Optional[str] = None) -> None:
        self._base_url = base_url.rstrip(\"/\")
        self._api_key = api_key

    def _call(self, function: str, args: dict[str, Any]) -> Any:
        url = f\"{{self._base_url}}/contracts/{{self.CONTRACT_ID}}/call\"
        body = json.dumps({{\"function\": function, \"args\": args}}).encode()
        req = urllib.request.Request(
            url,
            data=body,
            headers={{\"Content-Type\": \"application/json\"}},
        )
        if self._api_key:
            req.add_header(\"x-api-key\", self._api_key)
        with urllib.request.urlopen(req) as resp:
            data = json.loads(resp.read())
        return data.get(\"result\", {{}}). get(\"value\")
"
    );

    // Emit one method per function
    for f in &spec.functions {
        out.push('\n');
        let ret = py_return_type(f.output_tys.first());
        if f.inputs.is_empty() {
            let _ = writeln!(
                out,
                "    def {}(self) -> {ret}:",
                py_ident(&f.name)
            );
        } else {
            let params: Vec<String> = f
                .inputs
                .iter()
                .map(|i| format!("{}: {}", py_ident(&i.name), py_type(&i.ty)))
                .collect();
            let _ = writeln!(
                out,
                "    def {}(self, {}) -> {ret}:",
                py_ident(&f.name),
                params.join(", ")
            );
        }
        if !f.doc.trim().is_empty() {
            let _ = writeln!(out, "        \"\"\"{}\"\"\"", f.doc.trim().replace("\"\"\"", "\\\"\\\"\\\""));
        }
        if f.inputs.is_empty() {
            let _ = writeln!(out, "        return self._call({:?}, {{}})", f.name);
        } else {
            let arg_pairs: Vec<String> = f
                .inputs
                .iter()
                .map(|i| format!("{:?}: {}", i.name, py_ident(&i.name)))
                .collect();
            let _ = writeln!(
                out,
                "        return self._call({:?}, {{{}}})",
                f.name,
                arg_pairs.join(", ")
            );
        }
    }

    out
}

fn py_type(ty: &ScSpecTypeDef) -> String {
    use ScSpecTypeDef as T;
    match ty {
        T::Bool => "bool".into(),
        T::Void => "None".into(),
        T::U32 | T::I32 => "int".into(),
        T::U64 | T::I64 | T::U128 | T::I128 | T::U256 | T::I256 | T::Timepoint | T::Duration => {
            "INT".into()
        }
        T::String | T::Symbol => "str".into(),
        T::Address => "ADDRESS".into(),
        T::Bytes | T::BytesN(_) => "BYTES".into(),
        T::Option(o) => format!("Optional[{}]", py_type(&o.value_type)),
        T::Vec(v) => format!("list[{}]", py_type(&v.element_type)),
        T::Tuple(t) => {
            let inner: Vec<String> = t.value_types.iter().map(py_type).collect();
            format!("tuple[{}]", inner.join(", "))
        }
        T::Map(m) => format!("dict[str, {}]", py_type(&m.value_type)),
        T::Result(r) => py_type(&r.ok_type),
        T::Val | T::Error | T::MuxedAddress => "Any".into(),
        T::Udt(u) => u.name.to_utf8_string_lossy(),
    }
}

fn py_return_type(ty: Option<&ScSpecTypeDef>) -> String {
    ty.map_or_else(|| "None".into(), py_type)
}

fn py_ident(name: &str) -> String {
    // Python keywords that must be escaped
    match name {
        "from" | "class" | "import" | "return" | "def" | "lambda" | "pass" | "in" | "is"
        | "not" | "and" | "or" | "else" | "if" | "for" | "while" | "with" | "yield"
        | "raise" | "try" | "except" | "finally" | "del" | "global" | "nonlocal"
        | "assert" | "break" | "continue" | "as" | "type" => format!("{name}_"),
        _ => name.replace('-', "_"),
    }
}


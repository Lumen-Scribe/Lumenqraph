/// Generate a self-contained typed Rust client (`reqwest` + `serde`) for
/// `contract_id` from its on-chain interface.
pub fn rust_client(contract_id: &str, spec: &ContractSpec) -> String {
    let mut out = String::new();
    let _ = write!(
        out,
        "\
//! Typed client for the Soroban contract
//!   {contract_id}
//!
//! Generated by Lumenqraph from the contract's on-chain interface.
//! Depends on `reqwest` (with `json` feature) and `serde` / `serde_json`.
//!
//! Regenerate any time from `GET /contracts/{contract_id}/sdk?lang=rust`.

use serde::{{Deserialize, Serialize}};

pub const CONTRACT_ID: &str = {contract_id:?};

"
    );

    // Emit one struct per UDT struct
    for s in &spec.structs {
        let _ = writeln!(out, "#[derive(Debug, Clone, Serialize, Deserialize)]");
        let _ = writeln!(out, "pub struct {} {{", s.name);
        for f in &s.fields {
            let ty = rust_type(&f.ty);
            let _ = writeln!(out, "    pub {}: {ty},", rust_ident(&f.name));
        }
        out.push_str("}\n\n");
    }

    // Emit one enum per UDT enum
    for e in &spec.enums {
        let _ = writeln!(out, "#[derive(Debug, Clone, Serialize, Deserialize)]");
        let _ = writeln!(out, "pub enum {} {{", e.name);
        for (name, _) in &e.cases {
            let _ = writeln!(out, "    {name},");
        }
        out.push_str("}\n\n");
    }

    // Emit one enum per UDT union
    for u in &spec.unions {
        let _ = writeln!(out, "#[derive(Debug, Clone, Serialize, Deserialize)]");
        let _ = writeln!(out, "#[serde(untagged)]");
        let _ = writeln!(out, "pub enum {} {{", u.name);
        for c in &u.cases {
            if c.tys.is_empty() {
                let _ = writeln!(out, "    {},", c.name);
            } else if c.tys.len() == 1 {
                let ty = rust_type(&c.tys[0]);
                let _ = writeln!(out, "    {}({}),", c.name, ty);
            } else {
                let tys: Vec<String> = c.tys.iter().map(rust_type).collect();
                let _ = writeln!(out, "    {}({}),", c.name, tys.join(", "));
            }
        }
        out.push_str("}\n\n");
    }

    let _ = write!(
        out,
        "\
#[derive(Debug, Clone, Deserialize)]
struct CallResponse {{
    result: Option<ResultValue>,
}}

#[derive(Debug, Clone, Deserialize)]
struct ResultValue {{
    value: Option<serde_json::Value>,
}}

#[derive(Debug, Clone)]
pub struct ContractClient {{
    base_url: String,
    api_key: Option<String>,
    client: reqwest::Client,
}}

impl ContractClient {{
    pub fn new(base_url: impl Into<String>) -> Self {{
        Self {{
            base_url: base_url.into().trim_end_matches('/').to_string(),
            api_key: None,
            client: reqwest::Client::new(),
        }}
    }}

    pub fn with_api_key(mut self, key: impl Into<String>) -> Self {{
        self.api_key = Some(key.into());
        self
    }}

    async fn invoke(
        &self,
        function: &str,
        args: serde_json::Value,
    ) -> Result<Option<serde_json::Value>, reqwest::Error> {{
        let url = format!(\"{{base}}/contracts/{{cid}}/call\",
            base = self.base_url,
            cid = CONTRACT_ID);
        let body = serde_json::json!({{\"function\": function, \"args\": args}});
        let mut req = self.client.post(&url).json(&body);
        if let Some(key) = &self.api_key {{
            req = req.header(\"x-api-key\", key);
        }}
        let resp: CallResponse = req.send().await?.json().await?;
        Ok(resp.result.and_then(|r| r.value))
    }}
"
    );

    // Emit one method per function
    for f in &spec.functions {
        out.push('\n');
        if !f.doc.trim().is_empty() {
            for line in f.doc.trim().lines() {
                let _ = writeln!(out, "    /// {}", line.replace("*/", "* /"));
            }
        }
        let ret = rust_return_type(f.output_tys.first());
        if f.inputs.is_empty() {
            let _ = writeln!(
                out,
                "    pub async fn {}(&self) -> Result<{ret}, reqwest::Error> {{",
                rust_ident(&f.name)
            );
            let _ = writeln!(
                out,
                "        let v = self.invoke({:?}, serde_json::json!({{}})).await?;",
                f.name
            );
        } else {
            let params: Vec<String> = f
                .inputs
                .iter()
                .map(|i| {
                    let ty = rust_type(&i.ty);
                    format!("{}: {ty}", rust_ident(&i.name))
                })
                .collect();
            let _ = writeln!(
                out,
                "    pub async fn {}(&self, {}) -> Result<{ret}, reqwest::Error> {{",
                rust_ident(&f.name),
                params.join(", ")
            );
            let arg_pairs: Vec<String> = f
                .inputs
                .iter()
                .map(|i| format!("{:?}: {}", i.name, rust_ident(&i.name)))
                .collect();
            let _ = writeln!(
                out,
                "        let v = self.invoke({:?}, serde_json::json!({{{}}})).await?;",
                f.name,
                arg_pairs.join(", ")
            );
        }
        if f.output_tys.is_empty() {
            out.push_str("        let _ = v;\n        Ok(())\n    }\n");
        } else {
            out.push_str("        Ok(v)\n    }\n");
        }
    }

    out.push_str("}\n");
    out
}

fn rust_type(ty: &ScSpecTypeDef) -> String {
    use ScSpecTypeDef as T;
    match ty {
        T::Bool => "bool".into(),
        T::Void => "()".into(),
        T::U32 => "u32".into(),
        T::I32 => "i32".into(),
        T::U64 | T::Timepoint => "u64".into(),
        T::I64 | T::Duration => "i64".into(),
        T::U128 | T::U256 => "String".into(), // decimal strings for big ints
        T::I128 | T::I256 => "String".into(),
        T::String | T::Symbol => "String".into(),
        T::Address => "String".into(), // strkey
        T::Bytes | T::BytesN(_) => "String".into(), // hex
        T::Option(o) => format!("Option<{}>", rust_type(&o.value_type)),
        T::Vec(v) => format!("Vec<{}>", rust_type(&v.element_type)),
        T::Tuple(t) => {
            let inner: Vec<String> = t.value_types.iter().map(rust_type).collect();
            format!("({})", inner.join(", "))
        }
        T::Map(m) => format!(
            "std::collections::HashMap<String, {}>",
            rust_type(&m.value_type)
        ),
        T::Result(r) => rust_type(&r.ok_type),
        T::Val | T::Error | T::MuxedAddress => "serde_json::Value".into(),
        T::Udt(u) => u.name.to_utf8_string_lossy(),
    }
}

fn rust_return_type(ty: Option<&ScSpecTypeDef>) -> String {
    ty.map_or_else(|| "()".into(), rust_type)
}

fn rust_ident(name: &str) -> String {
    // Rust keywords
    match name {
        "type" | "self" | "fn" | "let" | "mut" | "use" | "mod" | "pub" | "impl" | "struct"
        | "enum" | "trait" | "match" | "if" | "else" | "for" | "while" | "loop" | "return"
        | "break" | "continue" | "where" | "as" | "in" | "ref" | "move" | "async" | "await"
        | "dyn" | "unsafe" | "extern" | "crate" | "super" | "static" | "const" | "box"
        | "true" | "false" => format!("r#{name}"),
        _ => name.replace('-', "_"),
    }
}

